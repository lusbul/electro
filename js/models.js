/* Фізичні моделі для інтерактивних схем.
   Кожна модель отримує параметри схеми й повертає стан: струм, яскравість, чи згорів LED. */
window.MODELS = {
  /* Готовий стан без розрахунку: { I, lamps, nets, meters } */
  fixed(p) { return { I: 0, ...p }; },

  /* Одна лампочка від батарейки (опір нитки ~100 Ом) */
  lamp1({ V = 9, RL = 100 }) { const I = V / RL * 1000; return { I, lamps: { L1: 1 } }; },

  /* Джерело + резистор: закон Ома */
  ohm({ V = 9, R = 1000 }) {
    const I = V / R * 1000; // мА
    return { I, level: 0, hot: false, burnt: false };
  },

  /* Джерело + резистор + світлодіод послідовно */
  ledSeries({ V = 9, R = 1000, Vf = 2, maxSafe = 30, burn = 60 }) {
    const I = Math.max(0, (V - Vf) / R) * 1000; // мА
    return {
      I,
      level: Math.min(1, I / 20),        // 20 мА — повна яскравість
      hot: I > maxSafe && I <= burn,
      burnt: I > burn
    };
  }
};

/* Стандартний ряд номіналів резисторів (E6, розширений) */
window.E_SERIES = [47, 68, 100, 150, 220, 330, 470, 680, 1000, 1500, 2200, 3300, 4700];
